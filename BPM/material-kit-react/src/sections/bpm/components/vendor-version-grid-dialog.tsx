import { useMemo, useState } from 'react';

import Box from '@mui/material/Box';
import Alert from '@mui/material/Alert';
import Stack from '@mui/material/Stack';
import Table from '@mui/material/Table';
import Button from '@mui/material/Button';
import Dialog from '@mui/material/Dialog';
import TableRow from '@mui/material/TableRow';
import TableBody from '@mui/material/TableBody';
import TableCell from '@mui/material/TableCell';
import TableHead from '@mui/material/TableHead';
import TextField from '@mui/material/TextField';
import Typography from '@mui/material/Typography';
import DialogTitle from '@mui/material/DialogTitle';
import DialogActions from '@mui/material/DialogActions';
import DialogContent from '@mui/material/DialogContent';
import TableContainer from '@mui/material/TableContainer';

import { isReadOnlyAutoGeneratedTemplateField } from 'src/sections/bpm/read-only-template-fields';
import {
  type VendorVersionBulkRow,
  uploadProcessVendorVersion,
} from 'src/sections/bpm/api';
import {
  type BpmProcess,
  type ActivityItem,
  type ActivityTemplate,
} from 'src/sections/bpm/storage';
import {
  templateFieldIsEmbeddedActivityName,
  templateFieldIsEmbeddedActivityDescription,
} from 'src/sections/bpm/template-field-classifiers';

type Props = {
  open: boolean;
  onClose: () => void;
  process: BpmProcess | null;
  selectedTemplate: ActivityTemplate | null;
  sortedActivities: ActivityItem[];
  /** Initial value when the user has no existing slot yet. */
  defaultVendorName: string;
  departmentId: string;
  processId: string;
  /** Existing overlay values keyed by activity.code so we pre-fill when re-uploading. */
  currentVendorKey: string;
  onUploaded: (next: BpmProcess) => void;
};

type VendorEditableField = {
  key: string;
  label: string;
  source: 'details' | 'activityName' | 'activityDescription';
};

function buildEditableFields(template: ActivityTemplate | null): VendorEditableField[] {
  if (template?.fields?.length) {
    const out: VendorEditableField[] = [];
    for (const field of template.fields) {
      if (templateFieldIsEmbeddedActivityName(field)) {
        out.push({ key: field.key, label: field.label || 'Activity Name', source: 'activityName' });
        continue;
      }
      if (templateFieldIsEmbeddedActivityDescription(field)) {
        out.push({
          key: field.key,
          label: field.label || 'Activity Description',
          source: 'activityDescription',
        });
        continue;
      }
      if (isReadOnlyAutoGeneratedTemplateField(field)) {
        continue;
      }
      out.push({ key: field.key, label: field.label || field.key, source: 'details' });
    }
    return out;
  }
  return [
    { key: 'activityName', label: 'Activity Name', source: 'activityName' },
    { key: 'activityDescription', label: 'Activity Description', source: 'activityDescription' },
  ];
}

function readOverlayCell(
  activity: ActivityItem,
  vendorKey: string,
  field: VendorEditableField,
): string {
  const overlay = activity.vendorVersions?.[vendorKey];
  if (!overlay) return '';
  if (field.source === 'activityName') return overlay.activityName ?? '';
  if (field.source === 'activityDescription') return overlay.activityDescription ?? '';
  const raw = overlay.details?.[field.key];
  if (raw === undefined || raw === null) return '';
  return Array.isArray(raw) ? raw.join(', ') : String(raw);
}

/** Parses a clipboard paste using TAB / newline as Excel does. */
function splitPaste(text: string): string[][] {
  if (!text) return [];
  return text.replace(/\r\n?/g, '\n').split('\n').map((line) => line.split('\t'));
}

export function VendorVersionGridDialog({
  open,
  onClose,
  process,
  selectedTemplate,
  sortedActivities,
  defaultVendorName,
  departmentId,
  processId,
  currentVendorKey,
  onUploaded,
}: Props) {
  const editableFields = useMemo(() => buildEditableFields(selectedTemplate), [selectedTemplate]);

  const initialMatrix = useMemo(
    () =>
      sortedActivities.map((activity) =>
        editableFields.map((field) => readOverlayCell(activity, currentVendorKey, field)),
      ),
    [sortedActivities, editableFields, currentVendorKey],
  );

  const [matrix, setMatrix] = useState<string[][]>(initialMatrix);
  const [vendorName, setVendorName] = useState<string>(defaultVendorName);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  // Reset matrix whenever the dialog opens for a different process / activities.
  useMemo(() => {
    if (open) {
      setMatrix(initialMatrix);
      setError('');
    }
  }, [open, initialMatrix]);

  const setCell = (rowIdx: number, colIdx: number, value: string) => {
    setMatrix((prev) => {
      if (!prev[rowIdx]) return prev;
      const nextRow = [...prev[rowIdx]];
      nextRow[colIdx] = value;
      const next = [...prev];
      next[rowIdx] = nextRow;
      return next;
    });
  };

  const onPasteIntoCell = (
    rowIdx: number,
    colIdx: number,
    event: React.ClipboardEvent<HTMLDivElement>,
  ) => {
    const text = event.clipboardData.getData('text');
    if (!text || (!text.includes('\t') && !text.includes('\n'))) {
      return; // single cell — let TextField handle natively
    }
    event.preventDefault();
    const rows = splitPaste(text);
    setMatrix((prev) => {
      const next = prev.map((row) => [...row]);
      rows.forEach((rowValues, r) => {
        rowValues.forEach((cellValue, c) => {
          const targetRow = rowIdx + r;
          const targetCol = colIdx + c;
          if (next[targetRow] && targetCol < editableFields.length) {
            next[targetRow][targetCol] = cellValue;
          }
        });
      });
      return next;
    });
  };

  const onSubmit = async () => {
    if (!process) return;
    const rows: VendorVersionBulkRow[] = [];
    sortedActivities.forEach((activity, idx) => {
      const cells = matrix[idx] ?? [];
      const hasAny = cells.some((value) => String(value ?? '').trim().length > 0);
      if (!hasAny) {
        return;
      }
      const details: Record<string, string | string[] | null> = {};
      let activityName: string | undefined;
      let activityDescription: string | undefined;
      editableFields.forEach((field, colIdx) => {
        const raw = String(cells[colIdx] ?? '').trim();
        if (field.source === 'activityName') {
          activityName = raw;
        } else if (field.source === 'activityDescription') {
          activityDescription = raw;
        } else {
          details[field.key] = raw.length ? raw : null;
        }
      });
      rows.push({
        activityCode: activity.code,
        activityName,
        activityDescription,
        details: Object.keys(details).length ? details : undefined,
      });
    });

    if (!rows.length) {
      setError('Fill at least one row before uploading.');
      return;
    }

    setBusy(true);
    setError('');
    try {
      const refreshed = await uploadProcessVendorVersion(departmentId, processId, {
        vendorName: vendorName.trim() || undefined,
        rows,
      });
      onUploaded(refreshed);
      onClose();
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setBusy(false);
    }
  };

  return (
    <Dialog open={open} onClose={busy ? undefined : onClose} maxWidth="xl" fullWidth>
      <DialogTitle>Upload my vendor version</DialogTitle>
      <DialogContent dividers>
        <Stack spacing={2}>
          <Alert severity="info">
            SI.No and Activity ID are locked to the Original numbering. Paste from Excel (Tab/Enter) into any cell to
            fill multiple cells at once. Leaving a cell empty keeps the previous value, if any.
          </Alert>
          <TextField
            size="small"
            label="Vendor display name"
            value={vendorName}
            onChange={(event) => setVendorName(event.target.value)}
            helperText="Shown next to your green-highlight rows."
            sx={{ maxWidth: 360 }}
          />
          {error ? <Alert severity="error">{error}</Alert> : null}
          <TableContainer sx={{ maxHeight: '60vh' }}>
            <Table size="small" stickyHeader sx={{ tableLayout: 'fixed' }}>
              <TableHead>
                <TableRow>
                  <TableCell sx={{ width: 64, fontWeight: 700 }}>SI.No</TableCell>
                  <TableCell sx={{ width: 140, fontWeight: 700 }}>Activity ID</TableCell>
                  {editableFields.map((field) => (
                    <TableCell key={field.key} sx={{ minWidth: 220, fontWeight: 700 }}>
                      {field.label}
                    </TableCell>
                  ))}
                </TableRow>
              </TableHead>
              <TableBody>
                {sortedActivities.map((activity, rowIdx) => (
                  <TableRow key={activity.id}>
                    <TableCell sx={{ bgcolor: 'grey.100' }}>{activity.sln}</TableCell>
                    <TableCell sx={{ bgcolor: 'grey.100', fontFamily: 'monospace' }}>{activity.code}</TableCell>
                    {editableFields.map((field, colIdx) => (
                      <TableCell key={field.key} sx={{ p: 0.5 }}>
                        <TextField
                          fullWidth
                          size="small"
                          multiline={field.source === 'activityDescription'}
                          minRows={field.source === 'activityDescription' ? 2 : 1}
                          value={matrix[rowIdx]?.[colIdx] ?? ''}
                          onChange={(event) => setCell(rowIdx, colIdx, event.target.value)}
                          onPaste={(event) => onPasteIntoCell(rowIdx, colIdx, event)}
                          disabled={busy}
                          sx={{
                            '& .MuiOutlinedInput-root': {
                              bgcolor: 'rgba(76, 175, 80, 0.08)',
                            },
                          }}
                        />
                      </TableCell>
                    ))}
                  </TableRow>
                ))}
                {!sortedActivities.length ? (
                  <TableRow>
                    <TableCell colSpan={2 + editableFields.length} sx={{ textAlign: 'center', py: 4 }}>
                      <Typography variant="body2" color="text.secondary">
                        This process has no Sub-processes yet — ask the Original owner to create them first.
                      </Typography>
                    </TableCell>
                  </TableRow>
                ) : null}
              </TableBody>
            </Table>
          </TableContainer>
        </Stack>
      </DialogContent>
      <DialogActions>
        <Box sx={{ flex: 1 }} />
        <Button onClick={onClose} disabled={busy} color="inherit">
          Cancel
        </Button>
        <Button variant="contained" color="success" onClick={() => void onSubmit()} disabled={busy}>
          {busy ? 'Uploading…' : 'Save vendor version'}
        </Button>
      </DialogActions>
    </Dialog>
  );
}
