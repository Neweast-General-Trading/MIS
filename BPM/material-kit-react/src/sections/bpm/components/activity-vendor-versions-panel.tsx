import { useMemo, useState } from 'react';

import Box from '@mui/material/Box';
import Card from '@mui/material/Card';
import Alert from '@mui/material/Alert';
import Stack from '@mui/material/Stack';
import Button from '@mui/material/Button';
import TextField from '@mui/material/TextField';
import Typography from '@mui/material/Typography';
import IconButton from '@mui/material/IconButton';

import { Iconify } from 'src/components/iconify';

import { patchActivityVendorVersion } from 'src/sections/bpm/api';
import { isReadOnlyAutoGeneratedTemplateField } from 'src/sections/bpm/read-only-template-fields';
import { type BpmProcess, type ActivityItem, type ActivityTemplate } from 'src/sections/bpm/storage';
import {
  templateFieldIsEmbeddedActivityName,
  templateFieldIsEmbeddedActivityDescription,
} from 'src/sections/bpm/template-field-classifiers';

type Props = {
  activity: ActivityItem;
  selectedTemplate: ActivityTemplate | null;
  departmentId: string;
  processId: string;
  /** Current user's lowercased email — used as the vendor key for inline edits. */
  currentVendorKey: string;
  /** True when the current user has the `vendorVersions` permission. */
  canEditOwnVendor: boolean;
  /** Display label for the current user's row when they don't have one stored yet. */
  defaultVendorName?: string;
  /** Refresh the process payload after a successful inline edit. */
  onProcessRefreshed: (next: BpmProcess) => void;
};

type FieldDescriptor = {
  key: string;
  label: string;
  /** Where the value lives on the activity (template details vs. top-level columns). */
  source: 'details' | 'activityName' | 'activityDescription';
  isReadOnly: boolean;
};

function readOriginalValue(activity: ActivityItem, field: FieldDescriptor): string {
  if (field.source === 'activityName') return activity.activityName ?? '';
  if (field.source === 'activityDescription') return activity.activityDescription ?? '';
  const raw = activity.details?.[field.key];
  if (raw === undefined || raw === null) return '';
  return Array.isArray(raw) ? raw.join(', ') : String(raw);
}

function readVendorValue(
  activity: ActivityItem,
  vendorKey: string,
  field: FieldDescriptor,
): string {
  const overlay = activity.vendorVersions?.[vendorKey];
  if (!overlay) return '';
  if (field.source === 'activityName') return overlay.activityName ?? '';
  if (field.source === 'activityDescription') return overlay.activityDescription ?? '';
  const raw = overlay.details?.[field.key];
  if (raw === undefined || raw === null) return '';
  return Array.isArray(raw) ? raw.join(', ') : String(raw);
}

/**
 * Builds the field list that should appear in the vendor overlay UI. Skips
 * server-generated columns (SI.No / Activity ID / hierarchy code) so vendors
 * can never alter the canonical numbering.
 */
function buildFieldDescriptors(
  activity: ActivityItem,
  template: ActivityTemplate | null,
): FieldDescriptor[] {
  if (template?.fields?.length) {
    const out: FieldDescriptor[] = [];
    for (const field of template.fields) {
      if (templateFieldIsEmbeddedActivityName(field)) {
        out.push({ key: field.key, label: field.label || 'Activity Name', source: 'activityName', isReadOnly: false });
        continue;
      }
      if (templateFieldIsEmbeddedActivityDescription(field)) {
        out.push({
          key: field.key,
          label: field.label || 'Activity Description',
          source: 'activityDescription',
          isReadOnly: false,
        });
        continue;
      }
      if (isReadOnlyAutoGeneratedTemplateField(field)) {
        // SI.No / Activity ID stay original-only.
        continue;
      }
      out.push({
        key: field.key,
        label: field.label || field.key,
        source: 'details',
        isReadOnly: false,
      });
    }
    return out;
  }

  // No template — fall back to the visible columns.
  const fallback: FieldDescriptor[] = [
    { key: 'activityName', label: 'Activity Name', source: 'activityName', isReadOnly: false },
    { key: 'activityDescription', label: 'Activity Description', source: 'activityDescription', isReadOnly: false },
  ];
  for (const detailKey of Object.keys(activity.details ?? {})) {
    fallback.push({ key: detailKey, label: detailKey, source: 'details', isReadOnly: false });
  }
  return fallback;
}

const ORIGINAL_BG = (alpha: number) => `rgba(244, 67, 54, ${alpha})`; // light red
const VENDOR_BG = (alpha: number) => `rgba(76, 175, 80, ${alpha})`; // light green

export function ActivityVendorVersionsPanel({
  activity,
  selectedTemplate,
  departmentId,
  processId,
  currentVendorKey,
  canEditOwnVendor,
  defaultVendorName,
  onProcessRefreshed,
}: Props) {
  const fields = useMemo(
    () => buildFieldDescriptors(activity, selectedTemplate),
    [activity, selectedTemplate],
  );

  const vendorEntries = useMemo(() => {
    const map = activity.vendorVersions ?? {};
    return Object.entries(map)
      .map(([key, value]) => ({ key, ...value }))
      .sort((a, b) => a.vendorName.localeCompare(b.vendorName));
  }, [activity.vendorVersions]);

  const currentVendor = vendorEntries.find((entry) => entry.key === currentVendorKey);

  const [editingFieldKey, setEditingFieldKey] = useState<string | null>(null);
  const [editingValue, setEditingValue] = useState<string>('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  const beginEdit = (field: FieldDescriptor) => {
    if (!canEditOwnVendor) return;
    setError('');
    const initial = currentVendor ? readVendorValue(activity, currentVendorKey, field) : '';
    setEditingFieldKey(field.key);
    setEditingValue(initial);
  };

  const commitEdit = async (field: FieldDescriptor) => {
    if (!canEditOwnVendor) return;
    setBusy(true);
    setError('');
    try {
      const payload: Parameters<typeof patchActivityVendorVersion>[3] = {
        vendorName: currentVendor?.vendorName || defaultVendorName,
      };
      const trimmed = editingValue.trim();
      if (field.source === 'activityName') {
        payload.activityName = trimmed;
      } else if (field.source === 'activityDescription') {
        payload.activityDescription = trimmed;
      } else {
        payload.details = { [field.key]: trimmed.length ? trimmed : null };
      }
      const refreshed = await patchActivityVendorVersion(
        departmentId,
        processId,
        activity.id,
        payload,
      );
      onProcessRefreshed(refreshed);
      setEditingFieldKey(null);
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setBusy(false);
    }
  };

  const cancelEdit = () => {
    setEditingFieldKey(null);
    setEditingValue('');
    setError('');
  };

  if (!fields.length) {
    return null;
  }

  return (
    <Card variant="outlined" sx={{ p: 2 }}>
      <Stack spacing={1.5}>
        <Stack direction="row" alignItems="center" justifyContent="space-between" spacing={1}>
          <Typography variant="subtitle1">Field values</Typography>
        </Stack>

        {error ? <Alert severity="error">{error}</Alert> : null}

        <Stack spacing={1.25}>
          {fields.map((field) => {
            const originalValue = readOriginalValue(activity, field);
            const isEditingThis = editingFieldKey === field.key;
            return (
              <Box key={field.key}>
                <Typography variant="caption" sx={{ fontWeight: 600, color: 'text.secondary' }}>
                  {field.label}
                </Typography>
                <Stack spacing={0.75} sx={{ mt: 0.5 }}>
                  <Box
                    sx={{
                      bgcolor: '#FFF7F7',
                      border: '1px solid',
                      borderColor: '#EED6D6',
                      borderRadius: 1.5,
                      px: 1.5,
                      py: 1,
                    }}
                  >
                    <Typography variant="body2" sx={{ whiteSpace: 'pre-wrap', wordBreak: 'break-word' }}>
                      {originalValue || '—'}
                    </Typography>
                  </Box>

                  {vendorEntries.map((entry) => {
                    const isOwnRow = entry.key === currentVendorKey;
                    const overlayDescriptor: FieldDescriptor = field;
                    const overlayValue = readVendorValue(activity, entry.key, overlayDescriptor);
                    if (isOwnRow && isEditingThis) {
                      return (
                        <Box
                          key={entry.key}
                          sx={{
                            bgcolor: VENDOR_BG(0.12),
                            borderLeft: '3px solid',
                            borderColor: VENDOR_BG(0.55),
                            borderRadius: 0.5,
                            px: 1.25,
                            py: 0.75,
                          }}
                        >
                          <Stack spacing={0.75} sx={{ flex: 1 }}>
                            <TextField
                              size="small"
                              multiline
                              minRows={field.source === 'activityDescription' ? 3 : 1}
                              value={editingValue}
                              onChange={(event) => setEditingValue(event.target.value)}
                              autoFocus
                              disabled={busy}
                            />
                            <Stack direction="row" spacing={1} justifyContent="flex-end">
                              <Button size="small" color="inherit" onClick={cancelEdit} disabled={busy}>
                                Cancel
                              </Button>
                              <Button
                                size="small"
                                variant="contained"
                                color="success"
                                onClick={() => void commitEdit(field)}
                                disabled={busy}
                              >
                                Save
                              </Button>
                            </Stack>
                          </Stack>
                        </Box>
                      );
                    }
                    if (!overlayValue.trim()) return null;
                    return (
                      <Box
                        key={entry.key}
                        sx={{
                          bgcolor: VENDOR_BG(0.12),
                          borderLeft: '3px solid',
                          borderColor: VENDOR_BG(0.55),
                          borderRadius: 0.5,
                          px: 1.25,
                          py: 0.75,
                          cursor: isOwnRow && canEditOwnVendor ? 'pointer' : 'default',
                        }}
                        onClick={() => (isOwnRow && canEditOwnVendor ? beginEdit(field) : null)}
                      >
                        <Stack direction="row" alignItems="flex-start" spacing={1}>
                          <Typography
                            variant="body2"
                            sx={{ whiteSpace: 'pre-wrap', wordBreak: 'break-word', flex: 1 }}
                          >
                            {overlayValue}
                          </Typography>
                          {isOwnRow && canEditOwnVendor ? (
                            <IconButton size="small" onClick={() => beginEdit(field)}>
                              <Iconify icon="solar:pen-bold" width={14} />
                            </IconButton>
                          ) : null}
                        </Stack>
                      </Box>
                    );
                  })}
                </Stack>
              </Box>
            );
          })}
        </Stack>
      </Stack>
    </Card>
  );
}

export { VENDOR_BG as VENDOR_OVERLAY_BG, ORIGINAL_BG as VENDOR_ORIGINAL_BG };
