import type { ActivityTemplateField } from 'src/sections/bpm/storage';

import { columnShowsHierarchySubProcessCode } from 'src/sections/bpm/hierarchy-code-display';
import { isServerGeneratedActivityDetailKey } from 'src/sections/bpm/server-generated-activity-fields';

/** Fields filled by the server (SLN, hierarchical code, stamped IDs) — not editable by users. */
export function isReadOnlyAutoGeneratedTemplateField(field: ActivityTemplateField): boolean {
  if (isServerGeneratedActivityDetailKey(field.key)) return true;
  if (columnShowsHierarchySubProcessCode(field.key, field.label)) return true;
  return false;
}

export function isReadOnlyAutoGeneratedDetailKey(key: string, label?: string): boolean {
  if (isServerGeneratedActivityDetailKey(key)) return true;
  if (columnShowsHierarchySubProcessCode(key, label)) return true;
  return false;
}
