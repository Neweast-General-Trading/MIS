/** Same output as the legacy “Download PDF” on the sub-processes table view. */
export function downloadSingleProcessActivitiesPdf(params: SingleProcessPdfParams) {
  const { processItem, sortedActivities, selectedTemplate, departmentName, departmentId, processId } = params;
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const margin = 38;
  const pageHeight = 842;
  const pageWidth = 595;
  const contentWidth = pageWidth - margin * 2;
  const generatedAt = new Date().toLocaleString();
  const state = { y: 56 };

  const ensureSpace = (requiredHeight: number, top = 56) => {
    if (state.y + requiredHeight > pageHeight - 44) {
      doc.addPage();
      state.y = top;
    }
  };

  const drawLabelValue = (label: string, value: string, labelX = margin, valueX = margin + 98) => {
    ensureSpace(24);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text(`${label}:`, labelX, state.y);
    doc.setFont('helvetica', 'normal');
    const valueLines = doc.splitTextToSize(value || '-', contentWidth - (valueX - margin));
    doc.text(valueLines, valueX, state.y);
    state.y += Math.max(18, valueLines.length * 14 + 2);
  };

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(`${processItem.code} | ${processItem.processName ?? processItem.name}`, margin, state.y);
  state.y += 30;

  drawLabelValue('Process Name', processItem.processName ?? processItem.name ?? '-');
  drawLabelValue('Status', summarizeProcessLineStatus(sortedActivities));
  drawLabelValue('Department', departmentName || '-');
  drawLabelValue('Process Owner', (processItem.processOwners ?? []).join(', ') || '-');
  state.y += 26;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('Process Description:', margin, state.y);
  state.y += 16;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  const processDescriptionLines = doc.splitTextToSize(
    processItem.processDescription ?? processItem.description ?? '-',
    contentWidth - 2,
  );
  doc.text(processDescriptionLines, margin, state.y);
  state.y += processDescriptionLines.length * 13.5 + 8;

  doc.setDrawColor(70);
  doc.line(margin, pageHeight - 56, pageWidth - margin, pageHeight - 56);

  doc.addPage();
  state.y = 58;

  const sectionAnchors = appendActivityDetailSections(
    doc,
    state,
    { margin, pageHeight, pageWidth, contentWidth },
    {
      processItem,
      sortedActivities,
      selectedTemplate,
      departmentId,
      processId,
      departmentName,
    },
  );

  doc.insertPage(2);
  doc.setPage(2);
  state.y = 64;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('Name Sub-Process:', margin, state.y);
  state.y += 26;

  const ensureSpaceToc = (requiredHeight: number, top = 64) => {
    if (state.y + requiredHeight > pageHeight - 44) {
      doc.addPage();
      state.y = top;
    }
  };

  sectionAnchors.forEach((anchor, index) => {
    ensureSpaceToc(92, 64);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);

    const titleText = `${index + 1}.  ${anchor.label}`;
    const linkDoc = doc as jsPDF & {
      textWithLink?: (text: string, x: number, y: number, options: { pageNumber: number; top?: number }) => void;
    };
    if (linkDoc.textWithLink) {
      linkDoc.textWithLink(titleText, margin, state.y, { pageNumber: anchor.pageNumber + 1, top: anchor.top });
    } else {
      doc.text(titleText, margin, state.y);
    }
    state.y += 22;
  });

  drawPdfFooter(doc, pageWidth, pageHeight, margin, generatedAt);

  doc.save(`${processItem.code}-process-template-style.pdf`);
}

async function resolveActivityTemplate(
  departmentId: string,
  processId: string,
  process: BpmProcess,
): Promise<ActivityTemplate | null> {
  let template: ActivityTemplate | null = null;
  try {
    template = await fetchProcessActivityTemplate(departmentId, processId);
  } catch {
    /* 403/404 while list still works */
  }
  if (!template && process.activityTemplateId) {
    try {
      const list = await fetchActivityTemplates();
      template = list.find((t) => t.id === process.activityTemplateId) ?? null;
    } catch {
      template = null;
    }
  }
  return template;
}

