/**
 * One PDF for the whole process function: cover (bold title) → process list →
 * each process with the same sub-process detail layout as the table PDF export.
 */
export async function downloadProcessFunctionBundlePdf(params: ProcessFunctionBundlePdfParams): Promise<void> {
  const { department, departmentId, processes, loadProcess } = params;
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const margin = 38;
  const pageHeight = 842;
  const pageWidth = 595;
  const contentWidth = pageWidth - margin * 2;
  const generatedAt = new Date().toLocaleString();
  const state = { y: 56 };
  const dim = { margin, pageHeight, pageWidth, contentWidth };

  const ensureSpace = (requiredHeight: number, top = 56) => {
    if (state.y + requiredHeight > pageHeight - 44) {
      doc.addPage();
      state.y = top;
    }
  };

  const drawLabelValue = (label: string, value: string, labelX = margin, valueX = margin + 98) => {
    ensureSpace(24);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text(`${label}:`, labelX, state.y);
    doc.setFont('helvetica', 'normal');
    const valueLines = doc.splitTextToSize(value || '-', contentWidth - (valueX - margin));
    doc.text(valueLines, valueX, state.y);
    state.y += Math.max(18, valueLines.length * 14 + 2);
  };

  // Page 1 — process function title (bold)
  const displayTitle = toDepartmentDisplayName(department.code, department.name);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  const titleLines = doc.splitTextToSize(displayTitle, contentWidth);
  doc.text(titleLines, margin, state.y);
  state.y += titleLines.length * 22 + 8;

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Process function code: ${department.code}`, margin, state.y);
  state.y += 14;
  if (department.companyCode) {
    doc.text(`Company: ${department.companyCode}`, margin, state.y);
    state.y += 14;
  }
  const owners = (department.processFunctionOwners ?? []).join(', ');
  if (owners) {
    doc.text(`Process function owners: ${owners}`, margin, state.y);
    state.y += 14;
  }
  doc.setFontSize(9);
  doc.setTextColor(90);
  doc.text(`Generated: ${generatedAt}`, margin, state.y);
  doc.setTextColor(0);
  state.y += 28;

  doc.addPage();
  state.y = 58;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('Process list', margin, state.y);
  state.y += 22;

  const listBody = processes.map((p, i) => [
    String(i + 1),
    p.code ?? '',
    p.processName?.trim() || p.name || '—',
    p.companyCode ?? '—',
    String(p.activities?.length ?? 0),
    summarizeProcessLineStatus([...(p.activities ?? [])].sort(compareActivityCodes)),
  ]);

  autoTable(doc, {
    startY: state.y,
    head: [['#', 'Code', 'Process name', 'Company', '# Sub-processes', 'Line status']],
    body: listBody.length ? listBody : [['—', '—', 'No processes', '—', '0', '—']],
    margin: { left: margin, right: margin },
    styles: { fontSize: 8.5, cellPadding: 3, overflow: 'linebreak' },
    headStyles: { fillColor: [55, 71, 79], textColor: 255 },
    theme: 'striped',
  });
  state.y = (doc as jsPDF & { lastAutoTable?: { finalY?: number } }).lastAutoTable?.finalY ?? state.y;
  state.y += 28;

  const departmentName = department.name?.trim() || '-';

  for (const stub of processes) {
    const full = await loadProcess(departmentId, stub.id);
    const template = await resolveActivityTemplate(departmentId, full.id, full);
    const sortedActivities = [...(full.activities ?? [])].sort((a, b) => compareActivityCodes(a, b));

    doc.addPage();
    state.y = 56;

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    const processHeading = `${full.code} — ${full.processName ?? full.name}`;
    const headingLines = doc.splitTextToSize(processHeading, contentWidth);
    doc.text(headingLines, margin, state.y);
    state.y += headingLines.length * 18 + 10;

    doc.setFontSize(10);
    drawLabelValue('Process Name', full.processName ?? full.name ?? '-');
    drawLabelValue('Status', summarizeProcessLineStatus(sortedActivities));
    drawLabelValue('Department', departmentName || '-');
    drawLabelValue('Process Owner', (full.processOwners ?? []).join(', ') || '-');
    state.y += 8;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('Process Description:', margin, state.y);
    state.y += 14;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    const descLines = doc.splitTextToSize(
      full.processDescription ?? full.description ?? '-',
      contentWidth - 2,
    );
    doc.text(descLines, margin, state.y);
    state.y += descLines.length * 13.5 + 16;

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.text('Sub-processes', margin, state.y);
    state.y += 20;

    appendActivityDetailSections(doc, state, dim, {
      processItem: full,
      sortedActivities,
      selectedTemplate: template,
      departmentId,
      processId: full.id,
      departmentName,
    });
  }

  drawPdfFooter(doc, pageWidth, pageHeight, margin, generatedAt);

  const safeCode = String(department.code ?? 'process-function').replace(/[^\w.-]+/g, '_');
  doc.save(`${safeCode}-process-function-bundle.pdf`);
}
