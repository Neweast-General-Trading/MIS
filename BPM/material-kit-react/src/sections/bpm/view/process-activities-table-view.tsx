function displaySiNo(activity: ActivityItem): string {
  const detailsEntries = Object.entries(activity.details ?? {});
  const fromDetails = detailsEntries.find(([k]) => {
    const nk = normalizeFieldKey(k);
    return nk === normalizeFieldKey('si_no') || nk === normalizeFieldKey('SI.No');
  })?.[1];
  if (fromDetails !== undefined && fromDetails !== null && String(fromDetails).trim() !== '') {
    return String(fromDetails);
  }
  return activity.sln !== undefined && activity.sln !== null ? String(activity.sln) : '';
}

